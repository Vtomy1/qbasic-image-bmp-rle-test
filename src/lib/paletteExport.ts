/**
 * Palette exporters for retro graphics software (.PAL and .GPL)
 * Supports GIMP/Aseprite/GrafX2 (.gpl), JASC-PAL (.pal), and Microsoft RIFF PAL (.pal)
 */

import { PalettePreset, RGBColor } from '../types';

export type PaletteExportFormat = 'jasc-pal' | 'riff-pal' | 'gpl';

export function getPalettePresetLabel(preset: PalettePreset): string {
  switch (preset) {
    case 'qbasic16':
      return 'QBasic 16 Colors';
    case 'vga256':
      return 'VGA BIOS 256 Colors';
    case 'custom16':
      return 'Adaptive 16 Colors';
    case 'custom256':
      return 'Adaptive 256 Colors';
    case 'ega16':
      return 'EGA 16 Colors';
    case 'cga0':
      return 'CGA Palette 0';
    case 'cga1':
      return 'CGA Palette 1';
    case 'gameboy':
      return 'Handheld 4-Shade';
    case 'amber-crt':
      return 'Amber Phosphor CRT';
    case 'green-crt':
      return 'Green Phosphor CRT';
    default:
      return 'QBasic Palette';
  }
}

/**
 * Generates a GIMP Palette (.gpl) text file.
 * Compatible with GIMP, Aseprite, LibreSprite, GrafX2, Krita, Pixelorama.
 */
export function exportPaletteToGpl(palette: RGBColor[], paletteName: string): string {
  const columns = palette.length <= 16 ? 8 : 16;
  const lines: string[] = [
    'GIMP Palette',
    `Name: ${paletteName}`,
    `Columns: ${columns}`,
    '# Generated by QBasic BMP Studio',
  ];

  palette.forEach((c, idx) => {
    const r = String(c.r).padStart(3, ' ');
    const g = String(c.g).padStart(3, ' ');
    const b = String(c.b).padStart(3, ' ');
    lines.push(`${r} ${g} ${b}\tIndex ${idx} (${c.hex})`);
  });

  return lines.join('\n') + '\n';
}

/**
 * Generates a JASC-PAL (.pal) text file.
 * Compatible with Paint Shop Pro, Aseprite, GraphicsGale, Pro Motion NG, GrafX2.
 */
export function exportPaletteToJascPal(palette: RGBColor[]): string {
  const lines: string[] = ['JASC-PAL', '0100', String(palette.length)];

  for (const c of palette) {
    lines.push(`${c.r} ${c.g} ${c.b}`);
  }

  return lines.join('\r\n') + '\r\n';
}

/**
 * Generates a binary Microsoft RIFF PAL (.pal) file.
 * Compatible with Windows SDK tools, TileStudio, DirectDraw/Win16/DOS utilities.
 */
export function exportPaletteToRiffPal(palette: RGBColor[]): Uint8Array {
  const numEntries = palette.length;
  // data chunk payload = 2 (palVersion) + 2 (palNumEntries) + 4 * numEntries
  const dataChunkSize = 4 + numEntries * 4;
  // RIFF payload = 4 ("PAL ") + 4 ("data") + 4 (dataChunkSize) + dataChunkSize
  const riffSize = 4 + 8 + dataChunkSize;
  const totalSize = 8 + riffSize;

  const buffer = new Uint8Array(totalSize);
  const view = new DataView(buffer.buffer);

  const writeAscii = (offset: number, text: string) => {
    for (let i = 0; i < text.length; i++) {
      buffer[offset + i] = text.charCodeAt(i);
    }
  };

  // RIFF header
  writeAscii(0, 'RIFF');
  view.setUint32(4, riffSize, true);
  writeAscii(8, 'PAL ');

  // 'data' subchunk
  writeAscii(12, 'data');
  view.setUint32(16, dataChunkSize, true);
  view.setUint16(20, 0x0300, true); // LOGPALETTE version 3.0
  view.setUint16(22, numEntries, true);

  let offset = 24;
  for (const c of palette) {
    buffer[offset] = c.r;
    buffer[offset + 1] = c.g;
    buffer[offset + 2] = c.b;
    buffer[offset + 3] = 0; // peFlags
    offset += 4;
  }

  return buffer;
}

/**
 * Triggers a browser download for the exported palette file.
 */
export function downloadPaletteFile(
  palette: RGBColor[],
  format: PaletteExportFormat,
  baseFilename: string,
  paletteName: string
): void {
  const cleanBase =
    baseFilename.replace(/\.[^/.]+$/, '').replace(/[^A-Za-z0-9_-]/g, '_') || 'palette';

  let blob: Blob;
  let filename: string;

  if (format === 'gpl') {
    const gplText = exportPaletteToGpl(palette, paletteName);
    blob = new Blob([gplText], { type: 'text/plain;charset=utf-8' });
    filename = `${cleanBase}.gpl`;
  } else if (format === 'riff-pal') {
    const riffBytes = exportPaletteToRiffPal(palette);
    blob = new Blob([riffBytes as unknown as BlobPart], { type: 'application/octet-stream' });
    filename = `${cleanBase}_riff.pal`;
  } else {
    const jascText = exportPaletteToJascPal(palette);
    blob = new Blob([jascText], { type: 'text/plain;charset=utf-8' });
    filename = `${cleanBase}.pal`;
  }

  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
