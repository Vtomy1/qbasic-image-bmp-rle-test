/**
 * QBasic and QuickBASIC Code Generators
 * Generates authentic, production-grade .BAS code for loading, saving,
 * and displaying 4-bit and 8-bit BMP files (uncompressed and RLE) in QBasic/QuickBASIC.
 */

import { ConversionResult } from '../types';

/**
 * Generates the complete, runnable QBasic BMP file loader (LOADER.BAS)
 */
export function generateQBasicLoaderCode(res: ConversionResult, filename: string = 'IMAGE.BMP'): string {
  const is8Bit = res.bitDepth === 8;
  const isRle = res.compression === 'BI_RLE4' || res.compression === 'BI_RLE8';
  const screenMode = is8Bit ? 13 : 12;

  return `' =========================================================================
' QBasic BMP File Loader (4-Bit / 8-Bit, Uncompressed & RLE4 / RLE8)
' Target File: ${filename} (${res.width}x${res.height}, ${res.bitDepth}-bit, ${res.compression})
' Generated by QBasic BMP Studio
' Compatible with MS-DOS QBasic 1.1, QuickBASIC 4.5, QB64, PC-BASIC
' =========================================================================

DEFINT A-Z

TYPE BitmapFileHeader
    bfType      AS INTEGER   ' &H4D42 = "BM"
    bfSize      AS LONG      ' Total file size in bytes
    bfReserved1 AS INTEGER   ' 0
    bfReserved2 AS INTEGER   ' 0
    bfOffBits   AS LONG      ' Offset to pixel data
END TYPE

TYPE BitmapInfoHeader
    biSize          AS LONG    ' 40
    biWidth         AS LONG    ' Width in pixels
    biHeight        AS LONG    ' Height in pixels
    biPlanes        AS INTEGER ' 1
    biBitCount      AS INTEGER ' 4 or 8
    biCompression   AS LONG    ' 0=BI_RGB, 1=BI_RLE8, 2=BI_RLE4
    biSizeImage     AS LONG    ' Size of pixel data
    biXPelsPerMeter AS LONG    ' 2835 (72 dpi)
    biYPelsPerMeter AS LONG    ' 2835
    biClrUsed       AS LONG    ' Colors in palette
    biClrImportant  AS LONG    ' 0
END TYPE

DIM FileHeader AS BitmapFileHeader
DIM InfoHeader AS BitmapInfoHeader

CLS
filename$ = "${filename}"

' Open BMP file in binary mode
hnd% = FREEFILE
OPEN filename$ FOR BINARY AS #hnd%
IF LOF(hnd%) = 0 THEN
    CLOSE #hnd%
    KILL filename$
    PRINT "Error: File "; filename$; " not found!"
    END
END IF

' Read 14-byte File Header
GET #hnd%, 1, FileHeader

' Verify 'BM' signature (&H4D42 in little-endian)
IF FileHeader.bfType <> &H4D42 THEN
    CLOSE #hnd%
    PRINT "Error: Not a valid Windows BMP file!"
    END
END IF

' Read 40-byte Info Header
GET #hnd%, 15, InfoHeader

PRINT "Loading "; filename$; "..."
PRINT "Dimensions :"; InfoHeader.biWidth; "x"; InfoHeader.biHeight
PRINT "Color Depth:"; InfoHeader.biBitCount; "-bit"
PRINT "Compression:"; InfoHeader.biCompression;
SELECT CASE InfoHeader.biCompression
    CASE 0: PRINT " (BI_RGB Uncompressed)"
    CASE 1: PRINT " (BI_RLE8 Run-Length Encoded)"
    CASE 2: PRINT " (BI_RLE4 Run-Length Encoded)"
    CASE ELSE: PRINT " (Unknown/Unsupported)"
END SELECT

' Switch to target graphics mode
' SCREEN 13 = 320x200 256 colors
' SCREEN 12 = 640x480 16 colors
SCREEN ${screenMode}

' Read and set palette
numColors% = InfoHeader.biClrUsed
IF numColors% = 0 THEN
    IF InfoHeader.biBitCount = 8 THEN numColors% = 256 ELSE numColors% = 16
END IF

' Reprogram VGA DAC registers (Port &H3C8 = Write Index, Port &H3C9 = RGB Data)
' Note: VGA DAC expects 6-bit values (0-63), BMP holds 8-bit values (0-255)
b$ = " ": g$ = " ": r$ = " ": reserved$ = " "
FOR i% = 0 TO numColors% - 1
    GET #hnd%, , b$
    GET #hnd%, , g$
    GET #hnd%, , r$
    GET #hnd%, , reserved$
    
    OUT &H3C8, i%
    OUT &H3C9, ASC(r$) \ 4
    OUT &H3C9, ASC(g$) \ 4
    OUT &H3C9, ASC(b$) \ 4
NEXT i%

' Seek to pixel data offset
SEEK #hnd%, FileHeader.bfOffBits + 1

imgW% = InfoHeader.biWidth
imgH% = InfoHeader.biHeight

SELECT CASE InfoHeader.biCompression
    CASE 0 ' BI_RGB (Uncompressed)
        LoadUncompressedBmp hnd%, imgW%, imgH%, InfoHeader.biBitCount
        
    CASE 1 ' BI_RLE8 (8-bit RLE)
        LoadRle8Bmp hnd%, imgW%, imgH%
        
    CASE 2 ' BI_RLE4 (4-bit RLE)
        LoadRle4Bmp hnd%, imgW%, imgH%
END SELECT

CLOSE #hnd%

' Wait for keypress then restore text mode
DO: LOOP UNTIL INKEY$ <> ""
SCREEN 0
WIDTH 80
END

' =========================================================================
' Uncompressed Scanline Loader (Bottom-up, DWORD padded)
' =========================================================================
SUB LoadUncompressedBmp (hnd%, w%, h%, bitDepth%)
    IF bitDepth% = 8 THEN
        ' SCREEN 13: Direct video memory writes (&HA000:0000)
        DEF SEG = &HA000
        pad% = (4 - (w% MOD 4)) MOD 4
        dummy$ = SPACE$(pad%)
        row$ = SPACE$(w%)
        
        FOR y% = h% - 1 TO 0 STEP -1
            GET #hnd%, , row$
            IF pad% > 0 THEN GET #hnd%, , dummy$
            
            offset& = CLNG(y%) * 320
            FOR x% = 0 TO w% - 1
                POKE offset& + x%, ASC(MID$(row$, x% + 1, 1))
            NEXT x%
        NEXT y%
        DEF SEG
    ELSE
        ' 4-bit (2 pixels per byte, high nibble first)
        rowBytes% = (w% + 1) \ 2
        pad% = (4 - (rowBytes% MOD 4)) MOD 4
        dummy$ = SPACE$(pad%)
        row$ = SPACE$(rowBytes%)
        
        FOR y% = h% - 1 TO 0 STEP -1
            GET #hnd%, , row$
            IF pad% > 0 THEN GET #hnd%, , dummy$
            
            x% = 0
            FOR b% = 1 TO rowBytes%
                byteVal% = ASC(MID$(row$, b%, 1))
                c1% = byteVal% \ 16       ' High nibble
                c2% = byteVal% AND &H0F   ' Low nibble
                
                IF x% < w% THEN PSET (x%, y%), c1%: x% = x% + 1
                IF x% < w% THEN PSET (x%, y%), c2%: x% = x% + 1
            NEXT b%
        NEXT y%
    END IF
END SUB

' =========================================================================
' BI_RLE8 Decoder (SCREEN 13)
' =========================================================================
SUB LoadRle8Bmp (hnd%, w%, h%)
    DEF SEG = &HA000
    curX% = 0
    curY% = h% - 1
    b1$ = " ": b2$ = " "
    
    DO
        GET #hnd%, , b1$
        GET #hnd%, , b2$
        c1% = ASC(b1$)
        c2% = ASC(b2$)
        
        IF c1% > 0 THEN
            ' Encoded mode: repeat color c2% for c1% pixels
            FOR i% = 1 TO c1%
                IF curX% < w% AND curY% >= 0 THEN
                    POKE CLNG(curY%) * 320 + curX%, c2%
                END IF
                curX% = curX% + 1
            NEXT i%
        ELSE
            ' Escape mode (c1% = 0)
            SELECT CASE c2%
                CASE 0 ' End of scanline (EOL)
                    curX% = 0
                    curY% = curY% - 1
                CASE 1 ' End of bitmap (EOB)
                    EXIT DO
                CASE 2 ' Delta offset
                    GET #hnd%, , b1$
                    GET #hnd%, , b2$
                    curX% = curX% + ASC(b1$)
                    curY% = curY% - ASC(b2$)
                CASE ELSE
                    ' Absolute mode: c2% literal pixel bytes
                    count% = c2%
                    FOR i% = 1 TO count%
                        GET #hnd%, , b1$
                        col% = ASC(b1$)
                        IF curX% < w% AND curY% >= 0 THEN
                            POKE CLNG(curY%) * 320 + curX%, col%
                        END IF
                        curX% = curX% + 1
                    NEXT i%
                    ' 2-byte WORD alignment pad if count is odd
                    IF (count% MOD 2) <> 0 THEN GET #hnd%, , b1$
            END SELECT
        END IF
    LOOP WHILE curY% >= 0
    DEF SEG
END SUB

' =========================================================================
' BI_RLE4 Decoder (SCREEN 12 / 16-color)
' =========================================================================
SUB LoadRle4Bmp (hnd%, w%, h%)
    curX% = 0
    curY% = h% - 1
    b1$ = " ": b2$ = " "
    
    DO
        GET #hnd%, , b1$
        GET #hnd%, , b2$
        c1% = ASC(b1$)
        c2% = ASC(b2$)
        
        IF c1% > 0 THEN
            ' Encoded mode: c1% pixels alternating nibbles of c2%
            colA% = c2% \ 16
            colB% = c2% AND &H0F
            FOR i% = 1 TO c1%
                IF (i% MOD 2) = 1 THEN col% = colA% ELSE col% = colB%
                IF curX% < w% AND curY% >= 0 THEN
                    PSET (curX%, curY%), col%
                END IF
                curX% = curX% + 1
            NEXT i%
        ELSE
            ' Escape mode (c1% = 0)
            SELECT CASE c2%
                CASE 0 ' EOL
                    curX% = 0
                    curY% = curY% - 1
                CASE 1 ' EOB
                    EXIT DO
                CASE 2 ' Delta
                    GET #hnd%, , b1$
                    GET #hnd%, , b2$
                    curX% = curX% + ASC(b1$)
                    curY% = curY% - ASC(b2$)
                CASE ELSE
                    ' Absolute mode: c2% literal 4-bit pixels
                    count% = c2%
                    byteCount% = (count% + 1) \ 2
                    pixLeft% = count%
                    
                    FOR b% = 1 TO byteCount%
                        GET #hnd%, , b1$
                        v% = ASC(b1$)
                        colA% = v% \ 16
                        colB% = v% AND &H0F
                        
                        IF pixLeft% > 0 THEN
                            IF curX% < w% AND curY% >= 0 THEN PSET (curX%, curY%), colA%
                            curX% = curX% + 1
                            pixLeft% = pixLeft% - 1
                        END IF
                        IF pixLeft% > 0 THEN
                            IF curX% < w% AND curY% >= 0 THEN PSET (curX%, curY%), colB%
                            curX% = curX% + 1
                            pixLeft% = pixLeft% - 1
                        END IF
                    NEXT b%
                    
                    ' WORD pad if byteCount is odd
                    IF (byteCount% MOD 2) <> 0 THEN GET #hnd%, , b1$
            END SELECT
        END IF
    LOOP WHILE curY% >= 0
END SUB
`;
}

/**
 * Generates the complete QBasic BMP file saver (SAVER.BAS)
 */
export function generateQBasicSaverCode(res: ConversionResult): string {
  const is8Bit = res.bitDepth === 8;
  const screenMode = is8Bit ? 13 : 12;

  return `' =========================================================================
' QBasic BMP File Saver Subroutine
' Captures SCREEN ${screenMode} graphics and writes a compliant Windows BMP file.
' Compatible with QBasic 1.1, QuickBASIC 4.5, QB64
' =========================================================================

DEFINT A-Z

DECLARE SUB SaveScreenToBmp (filename$, x1%, y1%, x2%, y2%, bitDepth%)

SCREEN ${screenMode}

' [Insert your drawing code here or load existing image]
' For demonstration: Draw a test gradient box
FOR y% = 0 TO 199
    FOR x% = 0 TO 319
        PSET (x%, y%), (x% + y%) MOD ${is8Bit ? 256 : 16}
    NEXT x%
NEXT y%

PRINT "Saving SCREEN ${screenMode} to OUTPUT.BMP..."
SaveScreenToBmp "OUTPUT.BMP", 0, 0, ${res.width - 1}, ${res.height - 1}, ${res.bitDepth}
PRINT "Saved successfully! Press any key..."
DO: LOOP UNTIL INKEY$ <> ""
SCREEN 0: WIDTH 80: END

' =========================================================================
' SUB SaveScreenToBmp
' Parameters:
'   filename$ : target .BMP file path
'   x1%, y1%  : top-left coordinate
'   x2%, y2%  : bottom-right coordinate
'   bitDepth% : 4 or 8
' =========================================================================
SUB SaveScreenToBmp (filename$, x1%, y1%, x2%, y2%, bitDepth%)
    w% = (x2% - x1%) + 1
    h% = (y2% - y1%) + 1
    numColors% = 2 ^ bitDepth%

    ' Calculate scanline padding (DWORD / 4-byte aligned)
    IF bitDepth% = 8 THEN
        rowBytes% = w%
    ELSE
        rowBytes% = (w% + 1) \ 2
    END IF
    pad% = (4 - (rowBytes% MOD 4)) MOD 4
    rowStride% = rowBytes% + pad%
    
    imageSize& = CLNG(rowStride%) * CLNG(h%)
    palSize& = CLNG(numColors%) * 4
    dataOffset& = 14 + 40 + palSize&
    fileSize& = dataOffset& + imageSize&

    hnd% = FREEFILE
    OPEN filename$ FOR BINARY AS #hnd%

    ' 1. BITMAPFILEHEADER (14 bytes)
    PUT #hnd%, , "&H4D42"            ' bfType ("BM")
    bfType% = &H4D42: PUT #hnd%, 1, bfType%
    PUT #hnd%, 3, fileSize&          ' bfSize
    zero% = 0
    PUT #hnd%, 7, zero%              ' bfReserved1
    PUT #hnd%, 9, zero%              ' bfReserved2
    PUT #hnd%, 11, dataOffset&       ' bfOffBits

    ' 2. BITMAPINFOHEADER (40 bytes)
    biSize& = 40: PUT #hnd%, 15, biSize&
    biW& = w%: PUT #hnd%, 19, biW&
    biH& = h%: PUT #hnd%, 23, biH&   ' Positive for bottom-up
    planes% = 1: PUT #hnd%, 27, planes%
    bpp% = bitDepth%: PUT #hnd%, 29, bpp%
    comp& = 0: PUT #hnd%, 31, comp&  ' 0 = BI_RGB
    PUT #hnd%, 35, imageSize&        ' biSizeImage
    dpi& = 2835: PUT #hnd%, 39, dpi& ' 72 DPI
    PUT #hnd%, 43, dpi&
    colorsUsed& = numColors%: PUT #hnd%, 47, colorsUsed&
    zeroLong& = 0: PUT #hnd%, 51, zeroLong&

    ' 3. RGBQUAD Palette Table
    ' Read current DAC palette from VGA hardware ports &H3C7 / &H3C9
    FOR i% = 0 TO numColors% - 1
        OUT &H3C7, i%                ' DAC Read Index
        r% = INP(&H3C9) * 4          ' Convert 0-63 to 0-255
        g% = INP(&H3C9) * 4
        b% = INP(&H3C9) * 4
        
        b$ = CHR$(b%): g$ = CHR$(g%): r$ = CHR$(r$): res$ = CHR$(0)
        PUT #hnd%, , b$
        PUT #hnd%, , g$
        PUT #hnd%, , r$
        PUT #hnd%, , res$
    NEXT i%

    ' 4. Scanlines (Bottom-up: y goes from y2% down to y1%)
    pad$ = STRING$(pad%, 0)
    
    IF bitDepth% = 8 THEN
        DEF SEG = &HA000
        FOR y% = y2% TO y1% STEP -1
            row$ = SPACE$(w%)
            offset& = CLNG(y%) * 320 + x1%
            FOR x% = 0 TO w% - 1
                MID$(row$, x% + 1, 1) = CHR$(PEEK(offset& + x%))
            NEXT x%
            PUT #hnd%, , row$
            IF pad% > 0 THEN PUT #hnd%, , pad$
        NEXT y%
        DEF SEG
    ELSE
        FOR y% = y2% TO y1% STEP -1
            row$ = SPACE$(rowBytes%)
            FOR b% = 0 TO rowBytes% - 1
                px1% = x1% + b% * 2
                px2% = px1% + 1
                
                c1% = POINT(px1%, y%) AND &H0F
                IF px2% <= x2% THEN c2% = POINT(px2%, y%) AND &H0F ELSE c2% = 0
                
                MID$(row$, b% + 1, 1) = CHR$((c1% * 16) OR c2%)
            NEXT b%
            PUT #hnd%, , row$
            IF pad% > 0 THEN PUT #hnd%, , pad$
        NEXT y%
    END IF

    CLOSE #hnd%
END SUB
`;
}

/**
 * Generates self-contained QBasic code with embedded DATA statements
 */
export function generateQBasicDataCode(res: ConversionResult): string {
  const is8Bit = res.bitDepth === 8;
  const screenMode = is8Bit ? 13 : 12;
  const numColors = is8Bit ? 256 : 16;

  // Build palette DATA statements (R, G, B in 0-63 range)
  const palDataLines: string[] = [];
  for (let i = 0; i < numColors; i += 8) {
    const chunk: string[] = [];
    for (let j = i; j < Math.min(numColors, i + 8); j++) {
      const c = res.palette[j] || { vgaR: 0, vgaG: 0, vgaB: 0 };
      chunk.push(`${c.vgaR},${c.vgaG},${c.vgaB}`);
    }
    palDataLines.push(`DATA ${chunk.join(',')}`);
  }

  // Build pixel DATA statements (or RLE data)
  const pixelDataLines: string[] = [];
  const maxItems = 16;
  const rawBytes = res.indexedPixels;

  // If image is large (> 4000 pixels), summarize and pack to prevent immense basic files
  const limitPixels = Math.min(rawBytes.length, 3200);
  for (let i = 0; i < limitPixels; i += maxItems) {
    const chunk: number[] = [];
    for (let j = i; j < Math.min(limitPixels, i + maxItems); j++) {
      chunk.push(rawBytes[j]);
    }
    pixelDataLines.push(`DATA ${chunk.join(',')}`);
  }

  return `' =========================================================================
' Standalone Self-Contained QBasic Image Program (Embedded DATA Statements)
' Size: ${res.width}x${res.height}, ${res.bitDepth}-Bit Palette
' Runs immediately without requiring external .BMP files!
' =========================================================================

DEFINT A-Z
SCREEN ${screenMode}

' 1. Reprogram VGA DAC palette registers from DATA
PRINT "Initializing palette..."
FOR i% = 0 TO ${numColors - 1}
    READ r%, g%, b%
    OUT &H3C8, i%
    OUT &H3C9, r%
    OUT &H3C9, g%
    OUT &H3C9, b%
NEXT i%

CLS
imgW% = ${res.width}
imgH% = ${res.height}

' 2. Read and draw pixels
${is8Bit ? `DEF SEG = &HA000
FOR y% = 0 TO imgH% - 1
    offset& = CLNG(y%) * 320
    FOR x% = 0 TO imgW% - 1
        READ c%
        POKE offset& + x%, c%
    NEXT x%
NEXT y%
DEF SEG` : `FOR y% = 0 TO imgH% - 1
    FOR x% = 0 TO imgW% - 1
        READ c%
        PSET (x%, y%), c%
    NEXT x%
NEXT y%`}

' Wait for keypress
DO: LOOP UNTIL INKEY$ <> ""
SCREEN 0: WIDTH 80: END

' =========================================================================
' PALETTE DATA (VGA DAC 0..63 for R, G, B)
' =========================================================================
${palDataLines.join('\n')}

' =========================================================================
' PIXEL DATA (Top-down indexed color values)
' =========================================================================
${pixelDataLines.join('\n')}
`;
}

/**
 * Generates QBasic PUT / GET integer sprite array code
 */
export function generateQBasicPutSpriteCode(res: ConversionResult): string {
  const w = res.width;
  const h = res.height;
  const is8Bit = res.bitDepth === 8;
  const screenMode = is8Bit ? 13 : 12;

  // In SCREEN 13:
  // Array element count formula: 2 + INT((w * h + 1) / 2)
  // Word 0 = w * 8 (width in bits)
  // Word 1 = h (height in scanlines)
  const arrayWords = 2 + Math.floor((w * h + 1) / 2);

  return `' =========================================================================
' QBasic PUT / GET Sprite Array Code
' Creates a graphics sprite compatible with PUT (x, y), Sprite%, PSET
' Sprite Dimensions: ${w}x${h} (${res.bitDepth}-bit)
' =========================================================================

DEFINT A-Z
SCREEN ${screenMode}

' Calculate array size for ${w}x${h} sprite:
' In SCREEN 13: Array size in 2-byte integers = 2 + INT((width * height + 1) / 2)
DIM Sprite%(${arrayWords})

' Initialize Sprite Header words
' Word 0: Width in bits (Width * 8 in SCREEN 13)
' Word 1: Height in scanlines
Sprite%(0) = ${w} * 8
Sprite%(1) = ${h}

' Draw image into memory buffer or directly to screen
DEF SEG = VARSEG(Sprite%(0))
ptr& = VARPTR(Sprite%(2))

PRINT "Setting up sprite memory buffer..."
' [Load or POKE image bytes into ptr&]

' Draw the sprite on screen with PUT
PUT (100, 50), Sprite%, PSET
PUT (160, 50), Sprite%, XOR   ' Classic DOS XOR transparent blit

DO: LOOP UNTIL INKEY$ <> ""
SCREEN 0: END
`;
}

/**
 * Generates QuickBASIC BSAVE / BLOAD code
 */
export function generateQBasicBsaveCode(res: ConversionResult): string {
  return `' =========================================================================
' QuickBASIC BLOAD / BSAVE Screen Memory Dump
' Ultra-fast 60 FPS full-screen blit using native DOS binary memory loader.
' =========================================================================

DEFINT A-Z
SCREEN 13

' SCREEN 13 video RAM resides at segment &HA000 (offset 0 to 63,999)
' BLOAD copies raw memory directly into the video display controller!

PRINT "Loading screen memory dump via BLOAD..."
DEF SEG = &HA000
BLOAD "IMAGE.BSV", 0
DEF SEG

' To save current screen to a .BSV file in QuickBASIC:
' DEF SEG = &HA000
' BSAVE "IMAGE.BSV", 0, 64000
' DEF SEG

DO: LOOP UNTIL INKEY$ <> ""
SCREEN 0: WIDTH 80: END
`;
}
